        "Подготовь краткий рабочий бриф до внесения изменений. Это один экономный проход двух ролей; "
        "не редактируй файлы и сначала просмотри релевантную структуру репозитория.\n\n"
        f"{ROLE_PROMPTS['analyst']}\n\n"
